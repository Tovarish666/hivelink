#!/bin/sh
# hivelink — хук udhcpc для РАЗВЕДКИ.
#
# Ничего не настраивает: ни адреса, ни маршрута, ни resolv.conf.
# Только записывает, что предложил модем, чтобы узнать его подсеть.
#
# Это принципиально: штатный скрипт udhcpc прописал бы DNS модема
# в системный резолвер и увёл резолвинг всего хоста в случайный модем.

case "$1" in
    bound|renew)
        printf '%s %s %s\n' "${ip:-}" "${router:-}" "${subnet:-}" \
            >"${HL_DHCP_OUT:-/run/hivelink/dhcp.out}"
        ;;
esac
exit 0
